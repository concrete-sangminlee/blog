#!/usr/bin/env node
/**
 * Regenerate src/styles/vendor/pretendard.css.
 *
 * Pretendard's full-Hangul package is 72 MB, so the font files stay on
 * jsDelivr. Its @font-face stylesheet, however, is vendored into our own
 * CSS bundle: a third-party stylesheet in <head> is render-blocking and
 * cost ~1.1 s of first paint on throttled mobile in Lighthouse. Each face
 * keeps its unicode-range, so browsers still fetch only the subsets a page
 * uses, and font-display: swap means the font files never block render.
 *
 * Run after bumping VERSION:  node scripts/vendor-pretendard.mjs
 */
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const VERSION = "1.3.9";
const DIR = `https://cdn.jsdelivr.net/npm/pretendard@${VERSION}/dist/web/variable`;
// The original (not jsDelivr's on-the-fly minified) file is immutable.
const SOURCE = `${DIR}/pretendardvariable-dynamic-subset.css`;
const OUT = path.join(import.meta.dirname, "..", "src", "styles", "vendor", "pretendard.css");

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
const css = await response.text();

const faces = css.match(/@font-face\s*{[^}]*}/g) ?? [];
if (faces.length < 50) throw new Error(`expected ~92 @font-face rules, got ${faces.length}`);

const compact = faces
  .map((face) =>
    face
      .replace(/url\((['"]?)\.?\/?(woff2-dynamic-subset\/[^)'"]+)\1\)/g, (_, _q, file) => `url(${DIR}/${file})`)
      .replace(/\s*([{};:,])\s*/g, "$1")
      .replace(/\s+/g, " ")
      .replace(/;}/g, "}"),
  )
  .join("\n");

if (/url\((?!https:)/.test(compact)) throw new Error("a relative url() survived the rewrite");

const digest = createHash("sha256").update(css).digest("hex");
const header = `/*
 * Pretendard Variable ${VERSION}, dynamic subset: @font-face rules only.
 * Generated by scripts/vendor-pretendard.mjs from
 * ${SOURCE}
 * (sha256 ${digest}). Do not edit by hand.
 *
 * Copyright (c) 2021 Kil Hyung-jin, with Reserved Font Name Pretendard.
 * Licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).
 */
`;

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, `${header}${compact}\n`);
console.log(`Wrote ${faces.length} @font-face rules to ${path.relative(process.cwd(), OUT)}`);
